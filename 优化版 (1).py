# ===== 通用工具函数 =====
def 稳健均价(序列):
    """优化①：中位数定价 + 1.5×IQR 异常值剔除。返回 (稳健中位数, 被剔除样本数)。
    与满帮参考价算法同源（历史成交中位数、剔除异常值）。"""
    序列 = [x for x in 序列 if x is not None]
    n = len(序列)
    if n == 0:
        return 0.0, 0
    s = sorted(序列)
    if n < 4:
        return statistics.median(s), 0
    q1 = statistics.quantiles(s, n=4)[0]
    q3 = statistics.quantiles(s, n=4)[2]
    iqr = q3 - q1
    lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
    干净 = [x for x in s if lo <= x <= hi]
    if not 干净:
        干净 = s
    return statistics.median(干净), n - len(干净)


