def 计算方案(车, 高速比例):
    车油耗 = 车型数据[车]["油耗"]
    车费率 = 车型数据[车]["费率"]
    车冷链 = 车型数据[车]["冷链系数"]
    高速段里程 = 里程 * 高速比例
    国道段里程 = 里程 * (1 - 高速比例) * 国道里程系数
    实里程 = 高速段里程 + 国道段里程
    油费_x = 高速段里程 / 100 * 车油耗 * oil + 国道段里程 / 100 * 车油耗 * 国道油耗系数 * oil
    通行费_x = 高速段里程 * 车费率
    if 绿色通道:                 # 鲜活农产品绿色通道：免高速通行费
        通行费_x = 0.0
    冷链费_x = 实里程 * 制冷费率 * 车冷链
    成本_x = 起步成本 + 油费_x + 通行费_x + 冷链费_x
    满载率_x = 计费重量 / 车型数据[车]["载重"]     # 优化③：用计费重量
    货重系数_x = 1.00 + 0.05 * min(满载率_x, 1.0)
