    # ---- 回测评估：点预测误差 + 区间覆盖率 ----
    def 回测(self, 库=None, 道路表=None, 车表=None, 产表=None, 口径=None):
        """在固定回测口径下，对历史订单库逐「线路×车型」组评估模型 M。"""
        库 = 历史订单库 if 库 is None else 库
        道路表 = 线路数据 if 道路表 is None else 道路表
        车表 = 车型数据 if 车表 is None else 车表
        产表 = 产品数据 if 产表 is None else 产表
        口径 = dict(产品="常温普货（建材 / 日用百货）", 道路方案="全程高速",
                     month="5-10月(正常)", 时段="平季（非旺季）", 油价=7.82, 回程配货=False) \
            if 口径 is None else 口径
        行 = []
        for 线路, 车map in 库.items():
            for 车型, 样本 in 车map.items():
                if not 样本:
                    continue
                货重 = round(车表[车型]["载重"] * 0.8, 1)
                res = self.predict(线路=线路, 车型=车型, 货重=货重, 货物体积=0.0,
                                   库=库, 道路表=道路表, 车表=车表, 产表=产表, **口径)
                真实 = 稳健均价(样本)[0]
                命中 = sum(1 for x in 样本 if res["下限"] <= x <= res["上限"]) / len(样本)
                行.append(dict(线路=线路, 车型=车型, 样本数=len(样本),
                               历史中位数=真实, 模型建议价=res["建议价"],
                               绝对误差=res["建议价"] - 真实,
                               相对误差=(res["建议价"] - 真实) / 真实,
                               区间命中率=命中, 场景=res["场景"], 置信度=res["置信度"]))
        n = len(行) or 1
        mae = sum(abs(r["绝对误差"]) for r in 行) / n
        mape = sum(abs(r["相对误差"]) for r in 行) / n
        rmse = math.sqrt(sum(r["绝对误差"] ** 2 for r in 行) / n)
        覆盖 = sum(r["区间命中率"] for r in 行) / n
        return dict(明细=行, 组数=len(行), MAE=mae, MAPE=mape, RMSE=rmse, 覆盖率=覆盖)

